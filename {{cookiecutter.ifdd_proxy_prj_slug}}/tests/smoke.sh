#!/usr/bin/env bash
# Starts the proxy with Docker Compose and checks it from the outside:
# health, HTTP to HTTPS redirect, dashboard authentication.
#
#   tests/smoke.sh development      # always possible
#   tests/smoke.sh production       # own certificates only: generates a
#                                   # throw-away certificate if none is there
#
# Leaves no trace: every file it creates is removed again.
set -euo pipefail
cd "$(dirname "$0")/.."

MODE=${1:-development}
COMPOSE=(docker compose -f "docker-compose-$MODE.yml")
HOST=proxy.localhost
USER_NAME=smoke
PASSWORD=$(openssl rand -hex 12)
CREATED=()

if [ "$MODE" = production ] && grep -q "^certificatesResolvers:" traefik/traefik.yml; then
  echo "SKIP  production smoke test: Let's Encrypt cannot issue certificates here"
  exit 0
fi

NETWORK=$(sed -n 's/^    name: //p' "docker-compose-$MODE.yml" | head -1)
CREATED_NETWORK=no

cleanup() {
  "${COMPOSE[@]}" down --volumes --remove-orphans >/dev/null 2>&1 || true
  for file in "${CREATED[@]}"; do rm -f "$file"; done
  [ "$CREATED_NETWORK" = yes ] && docker network rm "$NETWORK" >/dev/null 2>&1 || true
}
trap cleanup EXIT

# The shared network is external; create it only if it is missing, and
# remove it afterwards only in that case.
if ! docker network inspect "$NETWORK" >/dev/null 2>&1; then
  docker network create "$NETWORK" >/dev/null
  CREATED_NETWORK=yes
fi

[ -f .env ] || { cp dotenv.dist .env; CREATED+=(.env); }
export IFDD_PROXY_DASHBOARD_HOST=$HOST
set -a; . ./.env; set +a
export IFDD_PROXY_DASHBOARD_HOST=$HOST

if [ ! -f secrets/dashboard.htpasswd ]; then
  printf '%s:%s\n' "$USER_NAME" "$(openssl passwd -apr1 "$PASSWORD")" > secrets/dashboard.htpasswd
  CREATED+=(secrets/dashboard.htpasswd)
elif [ -n "${IFDD_PROXY_DASHBOARD_PASSWORD:-}" ]; then
  # Generated by the post-generation hook together with the htpasswd line.
  USER_NAME=$IFDD_PROXY_DASHBOARD_USER
  PASSWORD=$IFDD_PROXY_DASHBOARD_PASSWORD
else
  echo "secrets/dashboard.htpasswd exists; the credential check is skipped"
  PASSWORD=""
fi

TLS=no
grep -q "^  websecure:" "traefik/$([ "$MODE" = production ] && echo traefik.yml || echo traefik.development.yml)" && TLS=yes
if [ "$MODE" = production ] && [ "$TLS" = yes ]; then
  CERT=$(sed -n 's#^ *certFile: /certs/##p' traefik/dynamic/production/tls.yml)
  KEY=$(sed -n 's#^ *keyFile: /certs/##p' traefik/dynamic/production/tls.yml)
  if [ ! -f "certs/$CERT" ]; then
    openssl req -x509 -newkey rsa:2048 -nodes -days 1 -subj "/CN=$HOST" \
      -addext "subjectAltName=DNS:$HOST" -keyout "certs/$KEY" -out "certs/$CERT" 2>/dev/null
    CREATED+=("certs/$CERT" "certs/$KEY")
  fi
fi

"${COMPOSE[@]}" up -d --quiet-pull

for attempt in $(seq 30); do
  if "${COMPOSE[@]}" exec -T proxy traefik healthcheck --configFile=/etc/traefik/traefik.yml >/dev/null 2>&1; then
    echo "PASS  healthcheck"; break
  fi
  [ "$attempt" = 30 ] && { echo "FAIL  healthcheck"; "${COMPOSE[@]}" logs proxy; exit 1; }
  sleep 1
done

FAILURES=0
expect() {
  local name=$1 want=$2 got
  for _ in $(seq 10); do
    got=$(curl -sk -o /dev/null -w '%{http_code}' --max-time 5 "${@:3}" || true)
    [ "$got" = "$want" ] && break
    sleep 1   # the Docker provider needs a moment to pick up the labels
  done
  if [ "$got" = "$want" ]; then echo "PASS  $name"; else echo "FAIL  $name (got $got, want $want)"; FAILURES=$((FAILURES + 1)); fi
}

if [ "$TLS" = yes ]; then
  SCHEME=https; PORT=$IFDD_PROXY_HTTPS_PORT
  expect "http redirects to https" 301 --resolve "$HOST:$IFDD_PROXY_HTTP_PORT:127.0.0.1" "http://$HOST:$IFDD_PROXY_HTTP_PORT/dashboard/"
else
  SCHEME=http; PORT=$IFDD_PROXY_HTTP_PORT
fi
RESOLVE=(--resolve "$HOST:$PORT:127.0.0.1")
URL="$SCHEME://$HOST:$PORT/dashboard/"

expect "dashboard refuses anonymous access" 401 "${RESOLVE[@]}" "$URL"
if [ -n "$PASSWORD" ]; then
  expect "dashboard accepts valid credentials" 200 -u "$USER_NAME:$PASSWORD" "${RESOLVE[@]}" "$URL"
  expect "dashboard refuses a wrong password" 401 -u "$USER_NAME:wrong" "${RESOLVE[@]}" "$URL"
fi

if [ "$FAILURES" -gt 0 ]; then "${COMPOSE[@]}" logs proxy; exit 1; fi
echo "smoke test ($MODE) passed"
